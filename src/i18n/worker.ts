export function tr(text: string | undefined, lang: Lang): string {
  if (!text) return "";
  return text; // Placeholder for dynamic content
}

const STORAGE_KEY = "worker_lang";

export function getStoredLang(): Lang {
  if (typeof window === "undefined") return "en";
  const v = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
  return v && translations[v] ? v : "en";
}

export function setStoredLang(l: Lang) {
  if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, l);
}

export function makeT(lang: Lang) {
  return (key: keyof typeof translations["en"], vars?: Record<string, string | number>) => {
    let s = translations[lang]?.[key as string] ?? translations.en[key as string] ?? String(key);
    if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
}
